// ponytail: render-time guard closes the XSS at the only place it can fire —
// owner-authored URLs render on this shared page; only http(s) become links.
export const safeUrl = (u?: string) => (u && /^https?:\/\//i.test(u.trim()) ? u.trim() : null);

export default function Help() {
  const { user } = useAuth();
  const [topics, setTopics] = useState<HelpTopic[]>(DEFAULT_HELP_TOPICS);
  const [query, setQuery] = useState('');
  const [openTitles, setOpenTitles] = useState<Set<string>>(new Set());

  useEffect(() => {
    api.get('/settings/help')
      .then(r => {
        const help = r.data?.data;
        if (Array.isArray(help) && help.length > 0) setTopics(help);
      })
      .catch(() => { /* keep defaults */ });
  }, []);

  const q = query.trim().toLowerCase();
  const quickStart = user ? QUICK_START[user.role] : undefined;

  const groups = useMemo(() => {
    const visible = topics.filter(t => {
      if (t.roles && user && !t.roles.includes(user.role)) return false;
      if (!q) return true;
      return t.title.toLowerCase().includes(q) || (t.body ?? '').toLowerCase().includes(q);
    });
    const map = new Map<string, HelpTopic[]>();
    visible.forEach(t => {
      const cat = t.category || FALLBACK_CATEGORY;
      map.set(cat, [...(map.get(cat) ?? []), t]);
    });
    return [...map.entries()];
  }, [topics, user, q]);

  function toggle(title: string) {
    setOpenTitles(prev => {
      const next = new Set(prev);
      if (next.has(title)) next.delete(title); else next.add(title);
      return next;
    });
  }

  return (
    <div className="max-w-3xl mx-auto px-6 md:px-10 py-16 min-h-screen bg-background">
      <div className="mb-10">
        <span className="text-[10px] font-black uppercase tracking-[0.2em] text-primary mb-3 block">Справка</span>
        <h1 className="text-5xl font-serif text-surface font-light leading-tight tracking-tight">Помощь</h1>
        <p className="text-textSecondary mt-3 text-sm">Документация и руководство по работе с платформой.</p>
      </div>

      {quickStart && (
        <div className="mb-8 bg-primary/5 border border-primary/20 rounded-2xl px-8 py-6">
          <h2 className="text-[11px] font-black uppercase tracking-[0.15em] text-primary mb-3">Быстрый старт</h2>
          <ol className="space-y-2 list-decimal list-inside text-sm text-textPrimary">
            {quickStart.map((step, i) => <li key={i}>{step}</li>)}
          </ol>
        </div>
      )}

      <div className="mb-8">
        <Input
          type="search"
          placeholder="Найти ответ..."
          value={query}
          onChange={e => setQuery(e.target.value)}
          prefix={<Search className="w-4 h-4" />}
        />
      </div>

      {groups.length === 0 && (
        <p className="text-sm text-textSecondary text-center py-12">Ничего не найдено по запросу «{query}».</p>
      )}

      <div className="space-y-10">
        {groups.map(([category, items]) => (
          <div key={category}>
            <h2 className="text-[11px] font-black uppercase tracking-[0.15em] text-textSecondary/70 mb-3 px-1">
              {category}
            </h2>
            <div className="space-y-3">
              {items.map(item => {
                const href = safeUrl(item.url);
                const isOpen = !!q || openTitles.has(item.title);

                if (href) {
                  return (
                    <div key={item.title} className="bg-white rounded-2xl border border-border/20 px-8 py-6 shadow-sm">
                      <a
                        href={href}
                        target="_blank"
                        rel="noopener noreferrer"
                        className="font-bold text-surface text-sm mb-1 inline-flex items-center gap-1.5 hover:text-primary transition-colors"
                      >
                        {item.title}
                        <ExternalLink className="w-3.5 h-3.5 flex-shrink-0" />
                      </a>
                      {item.body && <p className="text-xs text-textSecondary mt-1 whitespace-pre-line">{item.body}</p>}
                    </div>
                  );
                }

                if (!item.body) {
                  return (
                    <div key={item.title} className="bg-white rounded-2xl border border-border/20 px-8 py-6 shadow-sm">
                      <p className="font-bold text-surface text-sm">{item.title}</p>
                    </div>
                  );
                }

                return (
                  <div key={item.title} className="bg-white rounded-2xl border border-border/20 shadow-sm overflow-hidden">
                    <button
                      type="button"
                      onClick={() => toggle(item.title)}
                      className="w-full flex items-center justify-between gap-3 text-left px-8 py-6"
                    >
                      <span className="font-bold text-surface text-sm">{item.title}</span>
                      <ChevronDown
                        className={`w-4 h-4 flex-shrink-0 text-textSecondary transition-transform ${isOpen ? 'rotate-180' : ''}`}
                      />
                    </button>
                    {isOpen && <p className="text-xs text-textSecondary px-8 pb-6 -mt-2 whitespace-pre-line">{item.body}</p>}
                  </div>
                );
              })}
            </div>
          </div>
        ))}
      </div>

      <div className="mt-12 border-t border-border/20 pt-8">
        <h2 className="text-[11px] font-black uppercase tracking-[0.15em] text-textSecondary/70 mb-4 px-1">Глоссарий</h2>
        <dl className="grid sm:grid-cols-2 gap-x-8 gap-y-3">
          {GLOSSARY.map(g => (
            <div key={g.term}>
              <dt className="text-xs font-bold text-surface">{g.term}</dt>
              <dd className="text-xs text-textSecondary mt-0.5">{g.def}</dd>
            </div>
          ))}
        </dl>
      </div>

      <div className="mt-12 text-center">
        <p className="text-xs text-textSecondary/50 uppercase tracking-widest font-bold">
          Есть вопросы? Обратитесь к администратору платформы.
        </p>
      </div>
    </div>
  );
}
